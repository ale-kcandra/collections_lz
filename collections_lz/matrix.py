import numpy as np # подключаем библиотеку для работы с матрицами
import random # подключаем библиотеку для генерации случайных чисел

n = int(input("Введите количество строк (N): ")) # введите количество строк
m = int(input("Введите количество столбцов (M): ")) # введите количество столбцов

matrix = np.random.randint(1, 10, size=(n, m)) # генерируем случайные числа от 1 до 10 размером N на M

print("\nИсходная матрица:") # выводим заголовок
print(matrix) # выводим матрицу

transposed_matrix = matrix.T # метод .T автоматически транспонирует матрицу
print("\nТранспонированная матрица:") # выводим заголовок
print(transposed_matrix) # выводим транспонированную матрицу

if n == m: # проверяем, является ли матрица квадратной
    det_original = np.linalg.det(matrix) # вычисляем определитель исходной матрицы
    det_transposed = np.linalg.det(transposed_matrix) # вычисляем определитель транспонированной матрицы
    
    print(f"\nОпределитель исходной матрицы: {det_original:.2f}") # выводим результат с 2 знаками после запятой
    print(f"Определитель транспонированной матрицы: {det_transposed:.2f}") # выводим результат
    
    if round(det_original, 5) == round(det_transposed, 5): # сравниваем значения, округляя до 5 знаков
        print("\nВывод: Определители равны! (Свойство определителя: det(A) = det(A^T))") # если равны
    else: # если не равны
        print("\nВывод: Определители НЕ равны.") # то выводим сообщение
else: # если матрица не квадратная
    print("\nОпределитель нельзя вычислить, так как матрица не квадратная (N != M).") # то выводим пояснение