import pandas as pd # подключаем библиотеку для работы с таблицами

df = pd.DataFrame(columns=["ФИО", "Адрес", "Телефон", "Дата рождения"]) # создаем пустую таблицу с нужными колонками
df.loc[0] = ["Иванов Иван Иванович", "Минск, ул. Марашал Лосика 30", "+375334567890", "01.01.2000"] # добавляем первую запись
df.loc[1] = ["Петров Петр Петрович", "Витебск, ул. Ленина 32", "+375294715199", "10.10.2010"] # добавляем вторую запись

print("исходная таблица") # выводим заголовок
print("") # пустая строка , чтобы лучше читать
print(df) # показываем таблицу 

df.loc[df["ФИО"] == "Петров Петр Петрович", "Телефон"] = "+375441112233" # находим Петрова и меняем ему телефон
print("после изменения телефона") # выводим заголовок
print(df) # показываем обновленную таблицу

df = df[df["ФИО"] != "Иванов Иван Иванович"] # оставляем только те строки, где ФИО не Иванов 
print("после удаления Иванова Ивана Ивановича") # выводим заголовок
print(df) # показываем итоговую таблицу